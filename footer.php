document.addEventListener('DOMContentLoaded', () => {
  const toTop = document.getElementById('agyToTop');
  if(toTop) {
    window.addEventListener('scroll', () => {
      if (window.scrollY > 300) {
        toTop.classList.add('show');
      } else {
        toTop.classList.remove('show');
      }
    });
    toTop.addEventListener('click', () => {
      window.scrollTo({ top: 0, behavior: 'smooth' });
    });
  }
  const fabToggle = document.getElementById('agyFabToggle');
  const fabMenu = document.getElementById('agyFabMenu');
  if(fabToggle && fabMenu) {
    fabToggle.addEventListener('click', (e) => {
      e.preventDefault();
      fabToggle.classList.toggle('active');
      fabMenu.classList.toggle('active');
    });
    document.addEventListener('click', (e) => {
      if(!fabToggle.contains(e.target) && !fabMenu.contains(e.target)) {
        fabToggle.classList.remove('active');
        fabMenu.classList.remove('active');
      }
    });
  }
  const contactBtn = document.getElementById('agyFabContactForm');
  if(contactBtn) {
    contactBtn.addEventListener('click', (e) => {
      e.preventDefault();
      if(fabToggle) fabToggle.classList.remove('active');
      if(fabMenu) fabMenu.classList.remove('active');
      const target = document.querySelector('#contact') || document.querySelector('#contact-form') || document.querySelector('.contact-section');
      if(target) {
        target.scrollIntoView({ behavior: 'smooth' });
      }
    });
  }
});
