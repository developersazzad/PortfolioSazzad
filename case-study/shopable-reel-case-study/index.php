    <div class="sec-head rv">
      <span class="kicker">01 · Overview</span>
      <h2 class="sec-title">A reel store inside <span class="grad-text">WordPress</span></h2>
      <p class="sec-lead">Shopable Reel brings the psychology of social video to a WooCommerce storefront —
        without subscriptions, without platform lock-in, without slowing the store down.</p>
    </div>

    <div class="ov-grid">
      <div class="ov-card rv" data-tilt="6">
        <span class="glare"></span>
        <h3><i>🎯</i> The Brief</h3>
        <p><b>Milanu</b>, a Bangladeshi fashion label running WooCommerce on the WoodMart theme, sells movement —
          flowing dupattas, swinging kurtis — through still photographs. Shoppers arriving from Facebook &amp; TikTok
          expected the same swipe-and-watch experience they get on social apps.</p>
        <p>The paid options were wrong for the job: <b>ReelUp</b> lives on Shopify and charges monthly;
          <b>Ecomm Reels</b> covers WordPress but offers little design or per-product control.
          So I built a free, self-owned plugin that is <b>easier than both</b>: one YouTube link per product,
          and the whole shoppable-reel experience assembles itself.</p>
        <p>Everything a merchant touches is AJAX-driven (no reloads), documented inside the admin
          (<b>Shortcode &amp; Help</b> screen), and exposed twice: as a drag-and-drop <b>Elementor widget</b>
          and as a <b>shortcode with 15+ optional attributes</b>.</p>
        <div class="quote">“If ReelUp can charge monthly for this on Shopify, WooCommerce merchants deserve
          something even easier — paste one YouTube link and the store starts selling in motion.”
          <small>— Sazzad Hossain · developersazzad</small></div>
      </div>

      <div class="ov-card rv" style="--d:.12s" data-tilt="6">
